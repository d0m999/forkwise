import { expect, test } from './writing-board-fixture';
import { createFrameCommand } from '../src/canvas-frame-commands';

test('整组从菜单复制为独立新组，只选新组且保留写字板绑定，一次撤销重做并重开', async ({ page, workspace }) => {
  const projectId = (await workspace.state()).project.id;
  await workspace.execute(page, { commandId: 'a', projectId, type: 'thought.create', expected: null, payload: { id: 'card', title: '研究正文', text: '需求增长', x: 100, y: 160 } });
  await workspace.execute(page, { commandId: 'b', projectId, type: 'shape.create', expected: null, payload: { id: 'shape', content: { shapeType: 'ellipse', shortText: '说明' }, pose: { x: 450, y: 160, width: 100, height: 60 } } });
  let s = await workspace.state();
  await workspace.execute(page, { commandId: 'group', projectId, type: 'group.create', expected: { groups: { bundle: null }, containment: Object.fromEntries([s.cards[0]!.item.id, s.shapes![0]!.item.id].map(id => [id, null])) }, payload: { id: 'bundle', itemIds: [s.cards[0]!.item.id, s.shapes![0]!.item.id] } });
  await page.reload(); await expect(page.getByRole('status')).toHaveText('已保存到本机');
  await page.getByRole('button', { name: '研究正文', exact: true }).click();
  await page.getByRole('button', { name: '编辑正文', exact: true }).click();
  await expect(page.getByRole('complementary', { name: '写字板', exact: true })).toBeVisible();
  await expect(page.locator('.body-editor small[title]')).toHaveAttribute('title', 'card');
  const sourceCard = page.getByRole('button', { name: '研究正文', exact: true });
  await sourceCard.focus(); await expect(sourceCard).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.locator('.react-flow__node.selected')).toHaveCount(0);
  await expect(page.locator('.body-editor small[title]')).toHaveAttribute('title', 'card');
  await sourceCard.click();
  await expect(page.locator('[data-group-id="bundle"]')).toHaveAttribute('data-selected', 'true');
  await expect(page.getByRole('button', { name: '进入组合', exact: true })).toBeVisible();
  const sourceGroup = (await workspace.state()).groups!.find(g => g.id === 'bundle')!;
  await expect.poll(async () => page.locator('.react-flow__node.selected').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-id')).sort())).toEqual([...sourceGroup.memberItemIds].sort());
  await page.getByRole('button', { name: '复制', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '复制副本', exact: true })).toBeVisible();
  await page.getByRole('menuitem', { name: '复制副本', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).groups!.length).toBe(2);
  s = await workspace.state();
  const copy = s.groups!.find(g => g.id !== 'bundle')!;
  expect(copy.memberItemIds).toHaveLength(2);
  await expect(page.getByRole('button', { name: '进入组合', exact: true })).toBeVisible();
  await expect(page.locator('.react-flow__node.selected')).toHaveCount(2);
  await expect.poll(async () => page.locator('.react-flow__node.selected').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-id')).sort())).toEqual([...copy.memberItemIds].sort());
  await expect(page.locator(`[data-group-id="${copy.id}"]`)).toHaveAttribute('data-selected', 'true');
  await expect(page.locator('[data-group-id="bundle"]')).toHaveAttribute('data-selected', 'false');
  await expect(page.locator('.body-editor small[title]')).toHaveAttribute('title', 'card');
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).groups!.length).toBe(1);
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).groups!.length).toBe(2);
  const saved = await workspace.state(); await workspace.restart(); await page.reload();
  await expect(page.getByRole('status')).toHaveText('已保存到本机');
  expect(await workspace.state()).toEqual(saved);
});

test('独立Frame选择支持空框键盘复制，菜单Escape与Tab保留，原名不加后缀', async ({ page, workspace }) => {
  await workspace.execute(page, createFrameCommand(await workspace.state(), [], { x: 150, y: 200, width: 400, height: 280 }));
  await page.reload(); await expect(page.getByRole('status')).toHaveText('已保存到本机');
  await page.getByRole('button', { name: '分区1', exact: true }).click();
  await page.getByRole('button', { name: '复制', exact: true }).click();
  await expect(page.getByRole('menuitem', { name: '复制到剪贴板', exact: true })).toBeVisible();
  await page.keyboard.press('Escape'); await expect(page.getByRole('button', { name: '复制', exact: true })).toBeFocused();
  await page.keyboard.press('Tab'); await page.keyboard.press('Meta+d');
  await expect.poll(async () => (await workspace.state()).frames!.length).toBe(2);
  const s = await workspace.state();
  expect(s.frames![1]!.name).toBe('分区1');
  expect(s.frames![1]!.pose).toEqual({ x: 174, y: 224, width: 400, height: 280 });
  await expect(page.locator('[data-frame-id][data-selected=true]')).toHaveCount(1);
  await expect(page.locator('.react-flow__node.selected')).toHaveCount(0);
});

test('多Frame根同批复制只选新根，多根Delete不写子集，点具体框收窄；undo后选择不复活', async ({ page, workspace }) => {
  await workspace.execute(page, createFrameCommand(await workspace.state(), [], { x: 150, y: 200, width: 220, height: 250 }));
  await workspace.execute(page, createFrameCommand(await workspace.state(), [], { x: 650, y: 200, width: 220, height: 250 }));
  await page.reload(); await expect(page.getByRole('status')).toHaveText('已保存到本机');
  await page.getByRole('button', { name: '分区1', exact: true }).click();
  await page.getByRole('button', { name: '分区2', exact: true }).click({ modifiers: ['Shift'] });
  await expect(page.locator('[data-frame-id][data-selected=true]')).toHaveCount(2);
  await page.keyboard.press('Meta+d');
  await expect.poll(async () => (await workspace.state()).frames!.length).toBe(4);
  const state = await workspace.state(), copies = state.frames!.slice(2), copyIds = copies.map(v => v.id).sort();
  await expect.poll(async () => page.locator('[data-frame-id][data-selected=true]').evaluateAll(nodes => nodes.map(n => n.getAttribute('data-frame-id')).sort())).toEqual(copyIds);
  await page.locator('.canvas').press('Delete');
  expect(await workspace.state()).toEqual(state);
  await page.locator(`[data-frame-id="${copies[0]!.id}"]`).getByRole('button', { name: '分区1', exact: true }).click();
  await expect(page.locator('[data-frame-id][data-selected=true]')).toHaveCount(1);
  await page.keyboard.press('Meta+d');
  await expect.poll(async () => (await workspace.state()).frames!.length).toBe(5);
  const fifth = (await workspace.state()).frames![4]!;
  await expect.poll(async () => page.locator('[data-frame-id][data-selected=true]').getAttribute('data-frame-id')).toBe(fifth.id);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).frames!.length).toBe(4);
  await expect(page.locator('[data-frame-id][data-selected=true]')).toHaveCount(0);
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).frames!.length).toBe(5);
  await expect(page.locator('[data-frame-id][data-selected=true]')).toHaveCount(0);
});
