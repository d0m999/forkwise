import { test, expect, place } from './writing-board-fixture';

test('卡面真实单行和长名省略，+N打开本卡完整标签，指针拖序只改变当前卡', async ({ page, workspace }) => {
  const names = ['这是需要完整保留但在卡面省略的很长标签名称'.repeat(4), 'Beta', 'Gamma', 'Delta', 'Epsilon', 'Zeta', 'Eta', 'Theta'];
  await place(page, '第一张', 80, 130); await place(page, '第二张', 470, 160);
  let state = await workspace.state(); const projectId = state.project.id;
  const run = (type: string, payload: object, expected: unknown = null) => workspace.execute(page, { commandId: crypto.randomUUID(), projectId, type, payload, expected });
  for (const [i, name] of names.entries()) await run('tag.create', { id: `tag-${i}`, name });
  const ids = names.map((_, i) => `tag-${i}`);
  for (const c of state.cards) await run('card.tags', { id: c.id, tagIds: ids });
  await page.reload(); await expect(page.getByRole('status')).toHaveText('已保存到本机');
  const card = page.locator('.react-flow__node').filter({ has: page.getByRole('button', { name: '第一张', exact: true }) });
  const row = card.locator('.card-visible-tags');
  const more = row.locator('.tag-overflow');
  await expect(more).toBeVisible();
  const visible = await row.locator('.project-tag').count();
  expect(visible).toBeGreaterThan(0); expect(visible).toBeLessThan(names.length);
  await expect(more).toHaveText(`+${names.length - visible}`);
  expect(await row.locator('.project-tag').first().evaluate(el => el.scrollWidth > el.clientWidth)).toBe(true);
  const layout = await row.evaluate(el => ({ h: el.getBoundingClientRect().height, ys: [...el.children].map(c => Math.round(c.getBoundingClientRect().y)), wrap: getComputedStyle(el).flexWrap }));
  expect(layout.h).toBeLessThanOrEqual(40); expect(new Set(layout.ys).size).toBe(1); expect(layout.wrap).toBe('nowrap');
  await more.click();
  const board = page.getByRole('complementary', { name: '写字板', exact: true });
  await expect(board.getByRole('heading')).toHaveText('正在编辑：第一张');
  await expect(board.locator('.board-tags .project-tag')).toHaveText(names);
  const handles = board.locator('.tag-drag');
  const first = handles.nth(0), second = handles.nth(1);
  await first.scrollIntoViewIfNeeded(); const a = (await first.boundingBox())!, b = (await second.boundingBox())!;
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2); await page.mouse.down();
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 12 }); await page.mouse.up();
  const order = [ids[1], ids[0], ...ids.slice(2)];
  await expect.poll(async () => (await workspace.state()).cards[0]!.cardTags?.tagIds).toEqual(order);
  state = await workspace.state(); expect(state.cards[1]!.cardTags!.tagIds).toEqual(ids);
  await expect(board.locator('.board-tags .project-tag')).toHaveText([names[1]!, names[0]!, ...names.slice(2)]);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).cards[0]!.cardTags?.tagIds).toEqual(ids);
  await expect(board.locator('.board-tags .project-tag')).toHaveText(names);
  await board.getByRole('button', { name: '管理标签', exact: true }).click();
  const inputs = board.locator('.tag-option input:not([type=checkbox])');
  const expectedNames = [...names].sort((a, b) => a.localeCompare(b));
  expect(await inputs.evaluateAll(els => els.map(e => (e as HTMLInputElement).value))).toEqual(expectedNames);
  await board.getByLabel('查找项目标签', { exact: true }).fill('Beta'); await expect(inputs).toHaveCount(1);
  await board.getByLabel('重命名 Beta', { exact: true }).fill('Alpha'); await board.getByLabel('重命名 Beta', { exact: true }).press('Enter');
  await expect.poll(async () => (await workspace.state()).tags!.find(t => t.id === 'tag-1')!.name).toBe('Alpha');
  await board.getByLabel('查找项目标签', { exact: true }).fill('');
  expect(await inputs.first().inputValue()).toBe('Alpha');
});
