import { test, expect, place } from './writing-board-fixture';

test('标签真实写字板入口创建、复用、共享改名和十色色板键盘焦点不产生额外历史', async ({ page, workspace }) => {
  await place(page, '标签卡片');
  await page.getByRole('button', { name: '编辑正文', exact: true }).click();
  const board = page.getByRole('complementary', { name: '写字板', exact: true });
  await expect(board.getByRole('button', { name: '管理标签', exact: true })).toBeVisible();
  await board.getByRole('button', { name: '管理标签', exact: true }).click();
  const manager = board.getByRole('region', { name: '项目标签' });
  const untagged = await workspace.state();
  await manager.getByLabel('新标签名称', { exact: true }).fill('AI');
  await manager.getByRole('button', { name: '创建标签', exact: true }).click();
  await expect(manager.getByRole('checkbox', { name: '添加 AI 到卡片', exact: true })).toBeVisible();
  await expect(manager.getByRole('checkbox', { name: '添加 AI 到卡片', exact: true })).toBeChecked();
  await manager.getByRole('checkbox', { name: '添加 AI 到卡片', exact: true }).check();
  await expect.poll(async () => (await workspace.state()).cards[0]!.item.heightPolicy?.necessaryHeight ?? 0).toBeGreaterThan(untagged.cards[0]!.item.heightPolicy?.necessaryHeight ?? 0);
  await expect.poll(async () => (await workspace.state()).cards[0]!.cardTags?.tagIds.length).toBe(1);
  const before = await workspace.state();
  expect(before.tags).toHaveLength(1); expect(before.tags![0]).toMatchObject({ name: 'AI', color: '#f1f0ec' });
  await manager.getByLabel('新标签名称', { exact: true }).fill('ai');
  await manager.getByRole('button', { name: '创建标签', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('已保存到本机');
  expect((await workspace.state()).tags).toEqual(before.tags);
  const trigger = manager.getByRole('button', { name: 'AI颜色：默认', exact: true });
  await trigger.click();
  const palette = manager.getByRole('group', { name: 'AI标签颜色', exact: true });
  await expect(palette.getByRole('button', { pressed: true })).toHaveAccessibleName('默认');
  await expect(palette.locator('[data-tag-swatch]')).toHaveCount(10);
  await expect(manager.locator('input[type=color]')).toHaveCount(0);
  await palette.getByRole('button', { name: '默认', exact: true }).press('ArrowRight');
  await expect(palette.getByRole('button', { name: '灰色', exact: true })).toBeFocused();
  await palette.getByRole('button', { name: '灰色', exact: true }).press('End');
  await expect(palette.getByRole('button', { name: '红色', exact: true })).toBeFocused();
  await palette.getByRole('button', { name: '红色', exact: true }).press('Home');
  await expect(palette.getByRole('button', { name: '默认', exact: true })).toBeFocused();
  expect((await workspace.state()).project.revision).toBe(before.project.revision);
  await palette.getByRole('button', { name: '默认', exact: true }).press('Escape');
  await expect(trigger).toBeFocused();
  await expect(page.locator('.react-flow__node.selected')).toHaveCount(1);
  await trigger.click(); await manager.getByRole('button', { name: '蓝色', exact: true }).click();
  await expect.poll(async () => (await workspace.state()).tags![0]!.color).toBe('#d9e7f1');
  const colored = await workspace.state();
  await manager.getByRole('button', { name: '蓝色', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('已保存到本机');
  expect((await workspace.state()).project.revision).toBe(colored.project.revision);
  await manager.getByRole('button', { name: '蓝色', exact: true }).press('Escape');
  await manager.getByLabel('重命名 AI', { exact: true }).fill('Ai');
  await manager.getByLabel('重命名 AI', { exact: true }).press('Enter');
  await expect.poll(async () => (await workspace.state()).tags![0]!.name).toBe('Ai');
  await expect(board.locator('.board-tags .project-tag')).toHaveText(['Ai']);
  await expect(page.locator('.card-visible-tags .project-tag')).toHaveText(['Ai']);
  await page.reload(); await expect(page.getByRole('status')).toHaveText('已保存到本机');
  expect((await workspace.state()).tags![0]).toMatchObject({ name: 'Ai', color: '#d9e7f1' });
});
